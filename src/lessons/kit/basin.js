// 只算一件事：一年里有多少泥沙（亿吨）从哪来、到哪去。
//   上游（头道拐以上）来的沙少：按图 4.7，1956—1986 年约 1.41 亿吨。
//   中游黄土高原是主要侵蚀区：不治理时，小浪底一带年均约 13.33 亿吨（图 4.7），减去上游的，约 11.9 亿吨来自中游。
//   三类水土保持措施各减掉一部分中游的来沙（比例是示意，只保证三样都做时和图 4.7 的 1987—2005 年量级相当：小浪底约 5.46 亿吨）。
//   小浪底水库拦沙：下泄的只剩约一成（图 4.7，2006—2016 年小浪底约 0.55 亿吨）。调水调沙：人造洪峰冲刷下游河床，入海（利津）多出约 0.47 亿吨（图 4.7：利津 1.02 亿吨）。
//   没有水库、不治理时，下游河道每年淤下约 13.33 − 9.78 ≈ 3.6 亿吨（图 4.7：利津 9.78 亿吨），河床一年年抬高。
// 注意：真实的输沙量减少，还和降水变化、上游水库、引水用水等有关；这里只把课本讲的水土保持、水库拦沙、调水调沙拿出来比。
export const UP = 1.41, MID0 = 13.33 - 1.41;
export const MEASURES = {
  bio: { name: '生物措施：封山育林、退耕还林还草', cut: 0.3 },
  farm: { name: '耕作措施：沿等高线耕作、少耕免耕', cut: 0.25 },
  eng: { name: '工程措施：修梯田、打坝淤地、挖鱼鳞坑', cut: 0.35 },
};
const LOWER_KEEP = 9.78 / 13.33;          // 没有水库时，进入下游的沙大约有这么多送到入海口，其余淤在河道里
export function loads({ bio = false, farm = false, eng = false, dam = false, flush = false } = {}) {
  let mid = MID0; for (const [k, on] of [['bio', bio], ['farm', farm], ['eng', eng]]) if (on) mid *= 1 - MEASURES[k].cut;
  const inflow = UP + mid, out = dam ? inflow * 0.1 : inflow;          // 小浪底：进库的沙、下泄的沙
  const sea = dam ? out + (flush ? 0.47 : 0.15) : inflow * LOWER_KEEP;          // 水库下泄的是清水，会冲刷下游河床；调水调沙冲得更多
  return { up: UP, mid, inflow, out, sea, deposit: out - sea };          // deposit：下游河道一年里淤下（正）或冲走（负）的泥沙
}
/** 下游河床一年抬高多少米（示意：每淤 1 亿吨约抬高 2.5 厘米，没有水库、不治理时约 9 厘米，和下游河床每年抬高几厘米到十几厘米的量级相当） */
export const bedRise = (deposit) => deposit * 0.025;
